package com.studentevents;

import java.sql.Connection;
import java.sql.Date;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.List;
import java.util.Scanner;

import com.studentevents.dao.EventDAO;
import com.studentevents.dao.RegistrationDAO;
import com.studentevents.dao.StudentDAO;
import com.studentevents.model.CampusEvent;
import com.studentevents.model.Registration;
import com.studentevents.model.Student;

/**
 * Main application console for Student Event Management.
 * Run directly in VS Code by pressing F5 or running this file.
 */
public class Main {

    private static final Scanner scanner = new Scanner(System.in);
    private static final EventDAO eventDAO = new EventDAO();
    private static final StudentDAO studentDAO = new StudentDAO();
    private static final RegistrationDAO registrationDAO = new RegistrationDAO();

    public static void main(String[] args) {
        printBanner();

        // 1. Verify Oracle Database connection
        System.out.println("Checking connection to Oracle Database Free (23c / 23ai)...");
        boolean connected = DatabaseConnection.testConnection();
        if (!connected) {
            System.out.println("\n[WARNING] Could not establish live connection to Oracle Free database.");
            System.out.println("Make sure: 1) Docker container is running (docker compose up -d)");
            System.out.println("           2) Setup SQL scripts in sql/ folder have been executed");
            System.out.println("           3) db.properties credentials match your Oracle instance.\n");
        }

        boolean running = true;
        while (running) {
            printMenu();
            System.out.print("Select an option (0-9): ");
            String choice = scanner.nextLine().trim();

            try {
                switch (choice) {
                    case "1" -> listEvents();
                    case "2" -> listStudents();
                    case "3" -> addStudent();
                    case "4" -> addEvent();
                    case "5" -> registerStudentPLSQL();
                    case "6" -> listRegistrations();
                    case "7" -> calculateRevenuePLSQL();
                    case "8" -> cancelRegistrationPLSQL();
                    case "9" -> viewAuditLogs();
                    case "0" -> {
                        System.out.println("\nExiting Student Event DBMS. Goodbye!");
                        running = false;
                    }
                    default -> System.out.println("Invalid selection. Please choose 0-9.");
                }
            } catch (SQLException ex) {
                System.err.println("\n>>> [Oracle / JDBC Error] " + ex.getMessage());
                System.err.println(">>> Error Code: " + ex.getErrorCode() + " | SQLState: " + ex.getSQLState());
            } catch (Exception ex) {
                System.err.println("\n>>> [Error] " + ex.getMessage());
            }

            if (running) {
                System.out.println("\nPress Enter to return to main menu...");
                scanner.nextLine();
            }
        }
    }

    private static void printBanner() {
        System.out.println("=======================================================================");
        System.out.println("       STUDENT EVENT MANAGEMENT SYSTEM - JAVA JDBC & ORACLE PL/SQL    ");
        System.out.println("           Oracle 23c Free Edition | VS Code Ready Console             ");
        System.out.println("=======================================================================");
    }

    private static void printMenu() {
        System.out.println("\n--- [STUDENT EVENT MANAGEMENT MENU] ---");
        System.out.println(" 1. View All Campus Events (PreparedStatement SELECT)");
        System.out.println(" 2. View All Registered Students");
        System.out.println(" 3. Add New Student (PreparedStatement INSERT)");
        System.out.println(" 4. Create New Campus Event (PreparedStatement INSERT)");
        System.out.println(" 5. Register Student for Event (CallableStatement -> PL/SQL Proc)");
        System.out.println(" 6. View All Registrations & Ticket Codes (Joined Query)");
        System.out.println(" 7. Calculate Event Total Revenue (CallableStatement -> PL/SQL Func)");
        System.out.println(" 8. Cancel Registration & Refund (CallableStatement -> PL/SQL Proc)");
        System.out.println(" 9. View Event Audit Logs (Generated by Oracle Triggers)");
        System.out.println(" 0. Exit");
        System.out.println("----------------------------------------");
    }

    private static void listEvents() throws SQLException {
        System.out.println("\n--- UPCOMING CAMPUS EVENTS ---");
        List<CampusEvent> events = eventDAO.getAllEvents();
        if (events.isEmpty()) {
            System.out.println("No events registered in database.");
            return;
        }
        for (CampusEvent e : events) {
            System.out.println(e);
        }
        System.out.println("Total events: " + events.size());
    }

    private static void listStudents() throws SQLException {
        System.out.println("\n--- REGISTERED STUDENTS ---");
        List<Student> students = studentDAO.getAllStudents();
        for (Student s : students) {
            System.out.println(s);
        }
        System.out.println("Total students: " + students.size());
    }

    private static void addStudent() throws SQLException {
        System.out.println("\n--- ADD NEW STUDENT (JDBC PreparedStatement) ---");
        System.out.print("Full Name: ");
        String name = scanner.nextLine();
        System.out.print("Email Address: ");
        String email = scanner.nextLine();
        System.out.print("Major (e.g. Computer Science): ");
        String major = scanner.nextLine();
        System.out.print("Year of Study (1-4): ");
        int yr = Integer.parseInt(scanner.nextLine());
        System.out.print("Phone Number: ");
        String phone = scanner.nextLine();

        Student s = new Student(0, name, email, major, yr, phone);
        if (studentDAO.addStudent(s)) {
            System.out.println(">>> Student added successfully via PreparedStatement!");
        }
    }

    private static void addEvent() throws SQLException {
        System.out.println("\n--- CREATE NEW CAMPUS EVENT (JDBC PreparedStatement) ---");
        System.out.print("Event Title: ");
        String title = scanner.nextLine();
        System.out.print("Category (Hackathon, Workshop, Seminar, Cultural, Sports): ");
        String category = scanner.nextLine();
        System.out.print("Event Date (YYYY-MM-DD): ");
        Date date = Date.valueOf(scanner.nextLine());
        System.out.print("Max Capacity (Seats): ");
        int capacity = Integer.parseInt(scanner.nextLine());
        System.out.print("Registration Fee ($): ");
        double fee = Double.parseDouble(scanner.nextLine());
        System.out.print("Venue / Location: ");
        String venue = scanner.nextLine();

        CampusEvent event = new CampusEvent(0, title, category, date, capacity, 0, fee, venue);
        if (eventDAO.createEvent(event)) {
            System.out.println(">>> Event created successfully!");
        }
    }

    private static void registerStudentPLSQL() throws SQLException {
        System.out.println("\n--- REGISTER STUDENT VIA PL/SQL STORED PROCEDURE ---");
        System.out.println("[Calls SP_REGISTER_STUDENT_EVENT: Checks capacity, generates unique ticket code, handles waitlist]");
        System.out.print("Enter Student ID (e.g. 201, 202): ");
        int stuId = Integer.parseInt(scanner.nextLine());
        System.out.print("Enter Event ID (e.g. 101, 102): ");
        int evtId = Integer.parseInt(scanner.nextLine());
        System.out.print("Fee Paid ($): ");
        double fee = Double.parseDouble(scanner.nextLine());

        var result = registrationDAO.registerStudentViaPLSQL(stuId, evtId, fee);
        System.out.println("\n>>> [PL/SQL Output]");
        System.out.println(">>> Registration ID: " + result.registrationId);
        System.out.println(">>> Status:          " + result.statusMessage);
        System.out.println(">>> Ticket Code:     " + result.ticketCode);
    }

    private static void listRegistrations() throws SQLException {
        System.out.println("\n--- CONFIRMED & WAITLISTED REGISTRATIONS ---");
        List<Registration> regs = registrationDAO.getAllRegistrations();
        if (regs.isEmpty()) {
            System.out.println("No registrations found.");
            return;
        }
        for (Registration r : regs) {
            System.out.println(r);
        }
    }

    private static void calculateRevenuePLSQL() throws SQLException {
        System.out.println("\n--- CALCULATE EVENT REVENUE (PL/SQL Stored Function) ---");
        System.out.print("Enter Event ID (e.g. 101): ");
        int evtId = Integer.parseInt(scanner.nextLine());

        double revenue = eventDAO.getEventRevenueViaPLSQL(evtId);
        System.out.printf(">>> Total Revenue collected for Event #%d: $%,.2f%n", evtId, revenue);
    }

    private static void cancelRegistrationPLSQL() throws SQLException {
        System.out.println("\n--- CANCEL REGISTRATION & PROCESS REFUND (PL/SQL Proc) ---");
        System.out.print("Enter Registration ID to cancel (e.g. 501): ");
        int regId = Integer.parseInt(scanner.nextLine());

        double refund = registrationDAO.cancelRegistrationViaPLSQL(regId);
        System.out.printf(">>> Registration #%d marked CANCELLED.%n", regId);
        System.out.printf(">>> Refund Processed: $%,.2f%n", refund);
        System.out.println(">>> If waitlisted students were present, the earliest applicant was automatically promoted!");
    }

    private static void viewAuditLogs() throws SQLException {
        System.out.println("\n--- EVENT AUDIT LOGS (Populated by Oracle PL/SQL Triggers) ---");
        String sql = "SELECT * FROM (SELECT log_id, table_name, action, record_id, details, logged_by, log_timestamp " +
                     "FROM event_audit_logs ORDER BY log_id DESC) WHERE ROWNUM <= 10";

        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql);
             ResultSet rs = stmt.executeQuery()) {

            System.out.printf("%-4s | %-14s | %-12s | %-6s | %-50s | %-20s%n",
                    "LOG", "TABLE", "ACTION", "REC_ID", "DETAILS", "TRIGGER / USER");
            System.out.println("-------------------------------------------------------------------------------------------------------------");
            while (rs.next()) {
                System.out.printf("%-4d | %-14s | %-12s | %-6d | %-50s | %-20s%n",
                        rs.getInt("log_id"),
                        rs.getString("table_name"),
                        rs.getString("action"),
                        rs.getInt("record_id"),
                        rs.getString("details"),
                        rs.getString("logged_by")
                );
            }
        }
    }
}
